#!/usr/bin/env python3
"""Generates scripts/common/constants_gen.py from ygopro-core's ocgapi_constants.h (the oracle's source, the
submodule ygopro-core-rust/oracle/ygopro-core: `git -C ygopro-core-rust submodule update --init oracle/ygopro-core`)."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "ygopro-core-rust" / "oracle" / "ygopro-core" / "ocgapi_constants.h"
EXTRA_HEADERS = [ROOT / "ygopro-core-rust" / "oracle" / "ygopro-core" / "common.h"]
OUT = ROOT / "scripts" / "common" / "constants_gen.py"

DEFINE_RE = re.compile(r"^\s*#define\s+([A-Z_][A-Z0-9_]*)\s+(.+?)\s*(?://.*)?$")


def to_python(expr: str) -> str:
    expr = expr.split("/*")[0].strip()
    expr = re.sub(r"\(\(uint64_t\)(\w+)\)", r"(\1)", expr)
    expr = re.sub(r"\(uint64_t\)", "", expr)
    # C octal literals such as 0001
    expr = re.sub(r"\b0([0-7]+)\b", r"0o\1", expr)
    return expr


def main() -> int:
    values: dict[str, int] = {}
    order: list[str] = []
    for header in [HEADER, *EXTRA_HEADERS]:
        for line in header.read_text().splitlines():
            m = DEFINE_RE.match(line)
            if not m:
                continue
            name, expr = m.group(1), to_python(m.group(2))
            if name.endswith("_H") or name.endswith("_H_") or not expr:
                continue
            try:
                value = eval(expr, {"__builtins__": {}}, dict(values))
            except Exception:
                continue
            if not isinstance(value, int):
                continue
            values[name] = value
            order.append(name)
    lines = [
        '"""Generated by scripts/gen_constants.py from ocgapi_constants.h. Do not edit."""',
        "",
    ]
    for name in order:
        lines.append(f"{name} = {values[name]:#x}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(order)} constants to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

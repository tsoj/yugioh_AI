"""Running duels: setup, the process loop, the arbiter and deterministic replays.

A game is fully determined by a GameRecord (decks, seeds and the responses of
both players), so records stay small; everything else (messages, per-player
observations, state snapshots) is regenerated by replaying.
"""

from __future__ import annotations

import random
import time
from dataclasses import dataclass, field

from . import constants as C
from .actions import encode
from .carddb import CardDB, default_db
from .core import Duel, DuelConfig
from .decks import Deck
from .messages import parse
from .observe import AUTO_RESPONSE, filter_message, filter_prompt, is_hidden_prompt, to_core_response
from .state import capture, view

RECORD_VERSION = 1


class GameError(RuntimeError):
    pass


def setup_duel(decks: list[Deck], core_seed: list[int], config: DuelConfig,
               deck_orders: list[list[int]], db: CardDB | None = None,
               copy_seed: int | None = None) -> Duel:
    """Creates a duel with canonical card ids.

    Cards are created in sorted code order (player 0 main, player 0 extra,
    player 1 main, player 1 extra) so that the relative card-id order of two
    different cards only depends on their codes. The core processes groups of
    cards in card-id order, which is visible (e.g. graveyard order), so this
    makes that order reproducible without knowing the hidden deck order.
    `deck_orders[p]` is the initial main deck order, bottom card first.

    With `copy_seed` (the arbiter's games), copies of the same card are put
    into their slots in random order: which physical copy (card id) is where is
    hidden information like the deck order itself, rather than following from
    the slot order.
    """
    duel = Duel(tuple(core_seed), config, db)
    for p in (0, 1):
        for code in sorted(decks[p].main):
            duel.new_card(p, code, C.LOCATION_DECK)
        for code in sorted(decks[p].extra):
            duel.new_card(p, code, C.LOCATION_EXTRA)
        if not duel.set_location_order(p, C.LOCATION_DECK, deck_orders[p]):
            raise GameError(f"deck order for player {p} does not match the deck list")
    if copy_seed is not None:
        import random
        rng = random.Random(copy_seed)
        for p in (0, 1):
            for loc in (C.LOCATION_DECK, C.LOCATION_EXTRA):
                cards = duel.location_cards(p, loc)
                slots: dict[int, list[int]] = {}
                for i, (code, _) in enumerate(cards):
                    slots.setdefault(code, []).append(i)
                ids = [cid for _, cid in cards]
                for code, pos in slots.items():
                    if len(pos) > 1:
                        chosen = [ids[i] for i in pos]
                        rng.shuffle(chosen)
                        for i, cid in zip(pos, chosen):
                            ids[i] = cid
                if not duel.set_location_order_by_id(p, loc, ids):
                    raise GameError(f"cannot place the copies of player {p}")
    return duel


@dataclass
class Step:
    messages: list[dict]
    prompt: dict | None
    ended: bool


def run_until_prompt(duel: Duel, pending_prompt: dict | None = None) -> Step:
    """Processes until a player has to respond or the duel ends."""
    msgs: list[dict] = []
    while True:
        status = duel.process()
        batch = [parse(m) for m in duel.get_messages()]
        msgs.extend(batch)
        if status == 0:  # OCG_DUEL_STATUS_END
            return Step(msgs, None, True)
        if status == 1:  # OCG_DUEL_STATUS_AWAITING
            if batch and batch[-1]["type"] != "RETRY":
                return Step(msgs[:-1], batch[-1], False)
            if pending_prompt is None:
                raise GameError("core awaits a response but no prompt was sent")
            return Step(msgs, pending_prompt, False)


@dataclass
class GameRecord:
    decks: list[Deck]
    seed: int
    core_seed: list[int]
    deck_orders: list[list[int]]
    config: dict
    responses: list[dict] = field(default_factory=list)  # {"player", "response"}
    result: dict = field(default_factory=dict)
    agents: list[str] = field(default_factory=list)

    def to_json(self) -> dict:
        return {"version": RECORD_VERSION, "decks": [d.to_json() for d in self.decks],
                "seed": self.seed, "core_seed": self.core_seed, "deck_orders": self.deck_orders,
                "config": self.config, "responses": self.responses, "result": self.result,
                "agents": self.agents}

    @staticmethod
    def from_json(d: dict) -> "GameRecord":
        return GameRecord(decks=[Deck.from_json(x) for x in d["decks"]], seed=d["seed"],
                          core_seed=d["core_seed"], deck_orders=d["deck_orders"],
                          config=d["config"], responses=d["responses"], result=d["result"],
                          agents=d.get("agents", []))

    def duel_config(self) -> DuelConfig:
        return DuelConfig(**self.config)


def new_record(decks: list[Deck], seed: int, config: DuelConfig | None = None) -> GameRecord:
    config = config or DuelConfig()
    rng = random.Random(seed)
    core_seed = [rng.getrandbits(64) for _ in range(4)]
    orders = []
    for d in decks:
        order = list(d.main)
        rng.shuffle(order)
        orders.append(order)
    return GameRecord(decks=list(decks), seed=seed, core_seed=core_seed, deck_orders=orders,
                      config={"flags": config.flags, "start_lp": config.start_lp,
                              "start_hand": config.start_hand,
                              "draw_per_turn": config.draw_per_turn})


def init_info(record: GameRecord, player: int) -> dict:
    """What a player knows before the duel starts."""
    own = record.decks[player]
    opp = record.decks[1 - player]
    return {"player": player, "deck": own.to_json(), "extra_order": sorted(own.extra),
            "opponent_deck_size": len(opp.main), "opponent_extra_size": len(opp.extra),
            "config": dict(record.config)}


class Observer:
    """Receives the god-view event stream of a duel."""

    def message(self, msg: dict) -> None:
        pass

    def prompt(self, prompt: dict, duel: Duel) -> None:
        pass

    def response(self, player: int, response: dict) -> None:
        pass


class ObservationLog(Observer):
    """Collects the observation stream of one player, as the arbiter would send it.

    Items are ("msg", filtered message), ("prompt", filtered prompt, state view)
    and ("response", response).
    """

    def __init__(self, player: int, with_state: bool = True):
        self.player = player
        self.with_state = with_state
        self.items: list[tuple] = []
        self._hidden = False

    def message(self, msg: dict) -> None:
        o = filter_message(msg, self.player)
        if o is not None:
            self.items.append(("msg", o))

    def prompt(self, prompt: dict, duel: Duel) -> None:
        self._hidden = is_hidden_prompt(prompt)
        if prompt["player"] != self.player or self._hidden:
            return
        state = view(capture(duel), self.player) if self.with_state else None
        self.items.append(("prompt", filter_prompt(prompt, self.player), state))

    def response(self, player: int, response: dict) -> None:
        if player == self.player and not self._hidden:
            self.items.append(("response", response))


class Forfeit(Exception):
    """Raised by an agent (or its clock) to lose the game immediately."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


@dataclass
class Clock:
    """Fischer time control for one player: `base` seconds plus `increment` per decision."""
    base: float
    increment: float = 0.0

    def __post_init__(self):
        self.remaining = self.base


def play(record: GameRecord, agents: list, max_decisions: int = 20000, max_turns: int = 100,
         observers: list[Observer] | None = None, db: CardDB | None = None,
         time_limit: float | None = None, clocks: list[Clock] | None = None,
         illegal_is_loss: bool = False) -> GameRecord:
    """Plays a game between two agents, filling record.responses and record.result.

    An agent loses immediately if it raises (e.g. Forfeit or a crashed engine),
    runs out of time on its clock, or - with `illegal_is_loss` - sends a
    response the core rejects. Otherwise invalid responses are asked again.
    """
    db = db or default_db()
    observers = observers or []
    duel = setup_duel(record.decks, record.core_seed, record.duel_config(), record.deck_orders, db,
                      copy_seed=record.core_seed[0])
    try:
        for p, agent in enumerate(agents):
            agent.start(p, init_info(record, p))
        record.agents = [getattr(a, "name", type(a).__name__) for a in agents]
        duel.start()
        prompt = None
        decisions = 0
        turns = 0
        retries = 0
        t0 = time.monotonic()
        result = None
        last_player = None
        while result is None:
            step = run_until_prompt(duel, prompt)
            for m in step.messages:
                for obs in observers:
                    obs.message(m)
                if m["type"] == "RETRY":
                    retries += 1
                    if illegal_is_loss and last_player is not None:
                        result = {"winner": 1 - last_player, "reason": "illegal_response"}
                    elif retries > 10:
                        result = {"winner": None, "reason": "retry_limit"}
                    continue
                for p, agent in enumerate(agents):
                    o = filter_message(m, p)
                    if o is not None:
                        agent.observe(o)
                if m["type"] == "NEW_TURN":
                    turns += 1
                elif m["type"] == "WIN":
                    result = {"winner": m["player"] if m["player"] < 2 else None,
                              "reason": m["reason"]}
            if result is not None:
                break
            if step.ended:
                result = {"winner": None, "reason": "ended"}
                break
            if turns > max_turns:
                result = {"winner": None, "reason": "turn_limit"}
                break
            if decisions >= max_decisions:
                result = {"winner": None, "reason": "decision_limit"}
                break
            if time_limit is not None and time.monotonic() - t0 > time_limit:
                result = {"winner": None, "reason": "time_limit"}
                break
            prompt = step.prompt
            player = prompt["player"]
            for obs in observers:
                obs.prompt(prompt, duel)
            agent = agents[player]
            t_move = time.monotonic()
            try:
                if is_hidden_prompt(prompt):
                    response = AUTO_RESPONSE
                else:
                    state = view(capture(duel), player) if agent.wants_state else None
                    response = agent.respond(filter_prompt(prompt, player), state)
                raw = encode(prompt, to_core_response(prompt, player, response))
            except Forfeit as e:
                result = {"winner": 1 - player, "reason": e.reason}
                break
            except Exception as e:  # noqa: BLE001 - a broken agent loses
                result = {"winner": 1 - player, "reason": f"agent_error: {type(e).__name__}: {e}"}
                break
            if clocks is not None:
                clock = clocks[player]
                clock.remaining -= time.monotonic() - t_move
                if clock.remaining < 0:
                    result = {"winner": 1 - player, "reason": "time_forfeit"}
                    break
                clock.remaining += clock.increment
            record.responses.append({"player": player, "response": response})
            for obs in observers:
                obs.response(player, response)
            duel.set_response(raw)
            last_player = player
            decisions += 1
        result.update({"turns": turns, "decisions": decisions, "retries": retries,
                       "script_errors": sum(1 for t, _ in duel.logs if t == 0)})
        record.result = result
        for agent in agents:
            agent.end(result)
        return record
    finally:
        duel.close()


def replay(record: GameRecord, observers: list[Observer], upto: int | None = None,
           db: CardDB | None = None) -> Duel:
    """Replays a recorded game, feeding observers; stops before response `upto`.

    Returns the live duel positioned at that prompt (the caller must close it).
    """
    db = db or default_db()
    duel = setup_duel(record.decks, record.core_seed, record.duel_config(), record.deck_orders, db,
                      copy_seed=record.core_seed[0])
    duel.start()
    responses = record.responses if upto is None else record.responses[:upto]
    prompt = None
    for entry in responses:
        step = run_until_prompt(duel, prompt)
        for m in step.messages:
            for obs in observers:
                obs.message(m)
        if step.ended:
            raise GameError("replay ended before all responses were used")
        prompt = step.prompt
        if prompt["player"] != entry["player"]:
            raise GameError("replay diverged: prompt for the wrong player")
        for obs in observers:
            obs.prompt(prompt, duel)
        for obs in observers:
            obs.response(entry["player"], entry["response"])
        duel.set_response(encode(prompt, to_core_response(prompt, entry["player"], entry["response"])))
    if upto is None:
        step = run_until_prompt(duel, prompt)
        for m in step.messages:
            for obs in observers:
                obs.message(m)
            if m["type"] == "WIN":
                break  # the core keeps going after a win; the game is over here
    return duel
